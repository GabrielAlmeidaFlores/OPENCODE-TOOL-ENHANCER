#!/usr/bin/env python3
"""
Generate the verified artifact catalog from the provenance registry.

Public API: none. The script is executed directly or through ``ote catalog build``.

Inputs: ``docs/provenance/registry.yml``.
Outputs: ``catalog/registry.json`` and ``catalog/index.md``.
Options: ``--check`` compares the generated output with the committed files and
exits non-zero on drift without writing.

Side effects: writes the two generated files unless ``--check`` is used.
References: docs/catalog/README.md, AGENTS.md Section 2A.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "docs/provenance/registry.yml"
OUTPUT = ROOT / "catalog/registry.json"
INDEX = ROOT / "catalog/index.md"

SECTIONS = {"agents": "agent", "skills": "skill", "commands": "command", "hats": "hat"}
REQUIRED = (
    "id",
    "local",
    "source",
    "upstream_path",
    "upstream_commit",
    "license",
    "author",
    "author_url",
    "retrieved",
    "modified",
)


def load_registry(path: Path) -> dict:
    try:
        import yaml
    except ImportError as error:
        raise SystemExit(
            "PyYAML is required to build the catalog. "
            f"Install it for this interpreter with: {sys.executable} -m pip install pyyaml"
        ) from error
    with path.open(encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise SystemExit(f"{path}: registry must be a mapping")
    return data


def artifact_entries(registry: dict) -> list[dict[str, str]]:
    catalog_entries: list[dict[str, str]] = []
    for section, artifact_type in SECTIONS.items():
        items = registry.get(section, [])
        if not isinstance(items, list):
            raise SystemExit(f"registry section {section} must be a list")
        for item in items:
            missing = [field for field in REQUIRED if not str(item.get(field, "")).strip()]
            if missing:
                raise SystemExit(f"{section}/{item.get('id', '?')}: missing {', '.join(missing)}")
            entry = {field: str(item[field]) for field in REQUIRED}
            entry["type"] = artifact_type
            entry["section"] = section
            catalog_entries.append(entry)
    order = {"agent": 0, "skill": 1, "command": 2, "hat": 3}
    return sorted(catalog_entries, key=lambda entry: (order.get(entry["type"], 9), entry["id"]))


def build_document(catalog_entries: list[dict[str, str]]) -> dict:
    counts: dict[str, int] = {}
    for entry in catalog_entries:
        counts[entry["type"]] = counts.get(entry["type"], 0) + 1
    return {
        "schema_version": 1,
        "generated_from": "docs/provenance/registry.yml",
        "counts": dict(sorted(counts.items())),
        "artifacts": catalog_entries,
    }


def render_index(document: dict) -> str:
    lines = [
        "# Artifact Catalog",
        "",
        "Generated from `docs/provenance/registry.yml` by `scripts/catalog/build_catalog.py`.",
        "Do not edit this file by hand.",
        "",
        "| Type | ID | Author | Source | License | Local path |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for entry in document["artifacts"]:
        lines.append(
            f"| {entry['type']} | `{entry['id']}` | {entry['author']} | {entry['source']} | "
            f"{entry['license']} | `{entry['local']}` |"
        )
    lines.append("")
    return "\n".join(lines)


def check_drift(document: dict, index: str) -> int:
    failures = 0
    expected_json = json.dumps(document, indent=2, sort_keys=True) + "\n"
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected_json:
        print(f"drift: {OUTPUT.relative_to(ROOT)} is not up to date")
        failures += 1
    if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != index:
        print(f"drift: {INDEX.relative_to(ROOT)} is not up to date")
        failures += 1
    if failures:
        print("run: python3 scripts/catalog/build_catalog.py")
    return 1 if failures else 0


def main(argv: list[str]) -> int:
    check = "--check" in argv
    registry = load_registry(REGISTRY)
    document = build_document(artifact_entries(registry))
    index = render_index(document)
    if check:
        return check_drift(document, index)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    INDEX.write_text(index, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(document['artifacts'])} artifacts)")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
