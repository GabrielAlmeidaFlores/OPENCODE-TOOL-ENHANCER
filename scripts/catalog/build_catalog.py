#!/usr/bin/env python3
"""
Generate the verified artifact catalog from the provenance registry.

Public API: none. The script is executed directly or through ``toolwright catalog build``.

Inputs: ``docs/provenance/registry.yml``.
Outputs: ``catalog/registry.json`` and ``catalog/index.md``.
Options: ``--check`` compares the generated output with the committed files and
exits non-zero on drift without writing.

Side effects: writes the two generated files unless ``--check`` is used.
References: docs/catalog/README.md, AGENTS.md Section 2A.
"""
from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scripts.lib.python_strings import (
    EMPTY_STRING,
    KEY_AGENT,
    KEY_AGENTS,
    KEY_COMMANDS,
    KEY_ID,
    KEY_SKILLS,
    TEXT_CATALOG_REGISTRY_JSON,
    TEXT_DOCS_PROVENANCE_REGISTRY_YML,
    TEXT_MAIN,
    TEXT_TEXT_5,
    TEXT_UTF_8,
)

import json
import sys
from pathlib import Path

FLAG_CHECK = '--check'
KEY_ARTIFACTS = 'artifacts'
KEY_AUTHOR = 'author'
KEY_AUTHOR_URL = 'author_url'
KEY_COMMAND = 'command'
KEY_COUNTS = 'counts'
KEY_GENERATED_FROM = 'generated_from'
KEY_HAT = 'hat'
KEY_HATS = 'hats'
KEY_LICENSE = 'license'
KEY_LOCAL = 'local'
KEY_MODIFIED = 'modified'
KEY_RETRIEVED = 'retrieved'
KEY_SCHEMA_VERSION = 'schema_version'
KEY_SECTION = 'section'
KEY_SKILL = 'skill'
KEY_SOURCE = 'source'
KEY_TYPE = 'type'
KEY_UPSTREAM_COMMIT = 'upstream_commit'
KEY_UPSTREAM_PATH = 'upstream_path'
TEXT_ARTIFACT_CATALOG = '# Artifact Catalog'
TEXT_CATALOG_INDEX_MD = 'catalog/index.md'
TEXT_DO_NOT_EDIT_THIS_FILE_BY_HAND = 'Do not edit this file by hand.'
TEXT_DRIFT_IS_NOT_UP_TO_DATE = 'drift: {} is not up to date'
TEXT_GENERATED_FROM_DOCS_PROVENANCE_REGISTRY_YML_BY_SCRIPTS_CATAL = 'Generated from [`docs/provenance/registry.yml`](../docs/provenance/registry.yml) by [`scripts/catalog/build_catalog.py`](../scripts/catalog/build_catalog.py).'
TEXT_MISSING = '{}/{}: missing {}'
TEXT_PYYAML_IS_REQUIRED_TO_BUILD_THE_CATALOG_INSTALL_IT_FOR_THIS_ = 'PyYAML is required to build the catalog. Install it for this interpreter with: {} -m pip install pyyaml'
TEXT_REGISTRY_MUST_BE_A_MAPPING = '{}: registry must be a mapping'
TEXT_REGISTRY_SECTION_MUST_BE_A_LIST = 'registry section {} must be a list'
TEXT_RUN_PYTHON3_SCRIPTS_CATALOG_BUILD_CATALOG_PY = 'run: python3 scripts/catalog/build_catalog.py'
TEXT_TEXT = '| {} | `{}` | {} | {} | {} | [`{}`](../{}) |'
TEXT_TEXT_2 = '?'
TEXT_TEXT_3 = ', '
TEXT_TEXT_4 = '| --- | --- | --- | --- | --- | --- |'
TEXT_TYPE_ID_AUTHOR_SOURCE_LICENSE_LOCAL_PATH = '| Type | ID | Author | Source | License | Local path |'
TEXT_WROTE = 'wrote {}'
TEXT_WROTE_ARTIFACTS = 'wrote {} ({} artifacts)'


ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / TEXT_DOCS_PROVENANCE_REGISTRY_YML
OUTPUT = ROOT / TEXT_CATALOG_REGISTRY_JSON
INDEX = ROOT / TEXT_CATALOG_INDEX_MD

SECTIONS = {KEY_AGENTS: KEY_AGENT, KEY_SKILLS: KEY_SKILL, KEY_COMMANDS: KEY_COMMAND, KEY_HATS: KEY_HAT}
REQUIRED = (
    KEY_ID,
    KEY_LOCAL,
    KEY_SOURCE,
    KEY_UPSTREAM_PATH,
    KEY_UPSTREAM_COMMIT,
    KEY_LICENSE,
    KEY_AUTHOR,
    KEY_AUTHOR_URL,
    KEY_RETRIEVED,
    KEY_MODIFIED,
)


def load_registry(path: Path) -> dict:
    try:
        import yaml
    except ImportError as error:
        raise SystemExit(
            TEXT_PYYAML_IS_REQUIRED_TO_BUILD_THE_CATALOG_INSTALL_IT_FOR_THIS_.format(sys.executable)
        ) from error
    with path.open(encoding=TEXT_UTF_8) as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise SystemExit(TEXT_REGISTRY_MUST_BE_A_MAPPING.format(path))
    return data


def artifact_entries(registry: dict) -> list[dict[str, str]]:
    catalog_entries: list[dict[str, str]] = []
    for section, artifact_type in SECTIONS.items():
        items = registry.get(section, [])
        if not isinstance(items, list):
            raise SystemExit(TEXT_REGISTRY_SECTION_MUST_BE_A_LIST.format(section))
        for item in items:
            missing = [field for field in REQUIRED if not str(item.get(field, EMPTY_STRING)).strip()]
            if missing:
                raise SystemExit(TEXT_MISSING.format(section, item.get(KEY_ID, TEXT_TEXT_2), TEXT_TEXT_3.join(missing)))
            entry = {field: str(item[field]) for field in REQUIRED}
            entry[KEY_TYPE] = artifact_type
            entry[KEY_SECTION] = section
            catalog_entries.append(entry)
    order = {KEY_AGENT: 0, KEY_SKILL: 1, KEY_COMMAND: 2, KEY_HAT: 3}
    return sorted(catalog_entries, key=lambda entry: (order.get(entry[KEY_TYPE], 9), entry[KEY_ID]))


def build_document(catalog_entries: list[dict[str, str]]) -> dict:
    counts: dict[str, int] = {}
    for entry in catalog_entries:
        counts[entry[KEY_TYPE]] = counts.get(entry[KEY_TYPE], 0) + 1
    return {
        KEY_SCHEMA_VERSION: 1,
        KEY_GENERATED_FROM: TEXT_DOCS_PROVENANCE_REGISTRY_YML,
        KEY_COUNTS: dict(sorted(counts.items())),
        KEY_ARTIFACTS: catalog_entries,
    }


def render_index(document: dict) -> str:
    lines = [
        TEXT_ARTIFACT_CATALOG,
        EMPTY_STRING,
        TEXT_GENERATED_FROM_DOCS_PROVENANCE_REGISTRY_YML_BY_SCRIPTS_CATAL,
        TEXT_DO_NOT_EDIT_THIS_FILE_BY_HAND,
        EMPTY_STRING,
        TEXT_TYPE_ID_AUTHOR_SOURCE_LICENSE_LOCAL_PATH,
        TEXT_TEXT_4,
    ]
    for entry in document[KEY_ARTIFACTS]:
        lines.append(
            TEXT_TEXT.format(entry[KEY_TYPE], entry[KEY_ID], entry[KEY_AUTHOR], entry[KEY_SOURCE], entry[KEY_LICENSE], entry[KEY_LOCAL], entry[KEY_LOCAL])
        )
    lines.append(EMPTY_STRING)
    return TEXT_TEXT_5.join(lines)


def check_drift(document: dict, index: str) -> int:
    failures = 0
    expected_json = json.dumps(document, indent=2, sort_keys=True) + TEXT_TEXT_5
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding=TEXT_UTF_8) != expected_json:
        print(TEXT_DRIFT_IS_NOT_UP_TO_DATE.format(OUTPUT.relative_to(ROOT)))
        failures += 1
    if not INDEX.is_file() or INDEX.read_text(encoding=TEXT_UTF_8) != index:
        print(TEXT_DRIFT_IS_NOT_UP_TO_DATE.format(INDEX.relative_to(ROOT)))
        failures += 1
    if failures:
        print(TEXT_RUN_PYTHON3_SCRIPTS_CATALOG_BUILD_CATALOG_PY)
    return 1 if failures else 0


def main(argv: list[str]) -> int:
    check = FLAG_CHECK in argv
    registry = load_registry(REGISTRY)
    document = build_document(artifact_entries(registry))
    index = render_index(document)
    if check:
        return check_drift(document, index)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(document, indent=2, sort_keys=True) + TEXT_TEXT_5, encoding=TEXT_UTF_8)
    INDEX.write_text(index, encoding=TEXT_UTF_8)
    print(TEXT_WROTE_ARTIFACTS.format(OUTPUT.relative_to(ROOT), len(document[KEY_ARTIFACTS])))
    print(TEXT_WROTE.format(INDEX.relative_to(ROOT)))
    return 0


if __name__ == TEXT_MAIN:
    sys.exit(main(sys.argv[1:]))
